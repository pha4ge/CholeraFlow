#!/usr/bin/env python3
"""Regenerate the report's vendored Lucide icon partial (development only).

The final HTML report never loads icons at runtime. This helper copies the inner
SVG markup of selected icons from a locally installed ``lucide-static`` package
(ISC licence; portions MIT from Feather) into a Jinja partial, so the icons are
embedded inline during report generation.

Usage (network access is only needed to obtain the package, not by this script):

    npm install --prefix /tmp/lucide lucide-static@0.544.0
    python3 scripts/vendor_report_icons.py \
        --lucide /tmp/lucide/node_modules/lucide-static

Only allow-listed element types and attributes are copied, so the generated
partial cannot carry scripts, event handlers or external references.
"""
import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets' / 'report_templates' / 'partials' / 'icons.html.j2'
LICENCE_OUTPUT = ROOT / 'assets' / 'report_templates' / 'LICENSES' / 'lucide-ISC.txt'

# Icons used by the report shell, sections and status vocabulary.
ICONS = sorted(set('''
activity arrow-down-to-line arrow-right arrow-up-right badge-check ban book-open
brackets calendar calendar-days calendar-range chart-bar chart-column chart-network
chart-no-axes-column chart-scatter check check-check chevron-down chevron-left
chevron-right chevron-up circle-alert circle-check circle-dashed circle-dot
circle-help circle-minus circle-x clipboard-list clock columns-3 copy crosshair
database dna download ellipsis-vertical expand eye eye-off file-check file-code
file-json file-spreadsheet file-text file-warning file-x filter fingerprint
flag flask-conical frame git-branch git-compare git-fork git-merge globe grid-3x3
hard-drive hash image inbox info keyboard layers layout-dashboard layout-grid
lightbulb link list list-checks lock map-pin maximize-2 menu message-square-text
microscope minimize-2 monitor moon mouse-pointer-click move network octagon-x
orbit package palette panel-left-close panel-left-open pill presentation printer
refresh-cw rotate-ccw route ruler scale scan scan-search scroll-text search
share-2 shield-alert shield-check shrink sigma sliders-horizontal spline split
square-dashed sun table table-2 tags test-tube triangle-alert type users
waypoints wifi-off workflow x zoom-in zoom-out
'''.split()))

ALLOWED = {
    'path': {'d'},
    'circle': {'cx', 'cy', 'r'},
    'rect': {'x', 'y', 'width', 'height', 'rx', 'ry'},
    'line': {'x1', 'y1', 'x2', 'y2'},
    'polyline': {'points'},
    'polygon': {'points'},
    'ellipse': {'cx', 'cy', 'rx', 'ry'},
}
SAFE_VALUE = re.compile(r'^[0-9A-Za-z .,\-]*$')


def inner_markup(path):
    root = ET.fromstring(path.read_text(encoding='utf-8'))
    parts = []
    for child in root:
        tag = child.tag.rsplit('}', 1)[-1]
        if tag not in ALLOWED:
            raise ValueError('{}: unsupported element {}'.format(path.name, tag))
        attrs = []
        for key, value in child.attrib.items():
            if key == 'fill' and value in ('currentColor', 'none'):
                attrs.append('{}="{}"'.format(key, value))
                continue
            if key not in ALLOWED[tag] or not SAFE_VALUE.match(value):
                raise ValueError('{}: unsupported attribute {}={!r}'.format(path.name, key, value))
            attrs.append('{}="{}"'.format(key, value))
        parts.append('<{} {}/>'.format(tag, ' '.join(attrs)))
    return ''.join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--lucide', required=True, type=Path,
                        help='Path to an installed lucide-static package directory')
    args = parser.parse_args()
    package = json.loads((args.lucide / 'package.json').read_text(encoding='utf-8'))
    icons = {name: inner_markup(args.lucide / 'icons' / '{}.svg'.format(name)) for name in ICONS}
    lines = [
        '{#- Generated by scripts/vendor_report_icons.py from lucide-static v'
        + package['version'] + ' (ISC; portions MIT from Feather).',
        '    Licence: assets/report_templates/LICENSES/lucide-ISC.txt. Do not edit by hand. -#}',
        '{%- set _CF_ICONS = {',
    ]
    for name in ICONS:
        lines.append("  '{}': '{}',".format(name, icons[name]))
    lines += [
        '} -%}',
        '{#- icon(name): decorative inline SVG (aria-hidden) unless a label is supplied. -#}',
        "{%- macro icon(name, cls='', label=none) -%}",
        '<svg class="cf-icon{% if cls %} {{ cls }}{% endif %}" viewBox="0 0 24 24" fill="none" '
        'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
        'focusable="false"{% if label %} role="img" aria-label="{{ label }}"{% else %} aria-hidden="true"{% endif %}>'
        "{{ _CF_ICONS.get(name, _CF_ICONS['circle-dashed'])|safe }}</svg>",
        '{%- endmacro -%}',
        '{#- icon_templates(): inert <template> clones for icons created by the report script. -#}',
        '{%- macro icon_templates() -%}',
        '<template id="cf-icon-templates">{% for name in _CF_ICONS %}'
        '<svg class="cf-icon" data-icon="{{ name }}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" focusable="false" aria-hidden="true">'
        '{{ _CF_ICONS[name]|safe }}</svg>{% endfor %}</template>',
        '{%- endmacro -%}',
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    LICENCE_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    LICENCE_OUTPUT.write_text((args.lucide / 'LICENSE').read_text(encoding='utf-8'), encoding='utf-8')
    print('Wrote {} icons to {}'.format(len(icons), OUTPUT))


if __name__ == '__main__':
    main()
